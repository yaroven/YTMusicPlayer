pub fn action_for(key: KeyEvent) -> Option<Action> {
    if key.modifiers.contains(KeyModifiers::CONTROL) {
        return (key.code == KeyCode::Char('c')).then_some(Action::Quit);
    }
    Some(match key.code {
        KeyCode::Char('q') => Action::Quit,
        KeyCode::Char('?') => Action::Help,
        KeyCode::Up | KeyCode::Char('k') => Action::Up,
        KeyCode::Down | KeyCode::Char('j') => Action::Down,
        KeyCode::PageUp => Action::PageUp,
        KeyCode::PageDown => Action::PageDown,
        KeyCode::Home | KeyCode::Char('g') => Action::Top,
        KeyCode::End | KeyCode::Char('G') => Action::Bottom,
        KeyCode::Tab | KeyCode::BackTab | KeyCode::Char('h') | KeyCode::Char('l') => {
            Action::FocusNext
        }
        KeyCode::Enter => Action::Select,
        KeyCode::Backspace | KeyCode::Char('b') => Action::Back,
        KeyCode::Char(' ') => Action::TogglePause,
        KeyCode::Char('n') => Action::Next,
        KeyCode::Char('p') => Action::Prev,
        KeyCode::Left => Action::SeekBack,
        KeyCode::Right => Action::SeekForward,
        KeyCode::Char('+') | KeyCode::Char('=') => Action::VolumeUp,
        KeyCode::Char('-') => Action::VolumeDown,
        KeyCode::Char('r') => Action::Sync,
        KeyCode::Char('/') => Action::Search,
        KeyCode::Char('o') => Action::FindOnline,
        KeyCode::Char('[') => Action::CategoryPrev,
        KeyCode::Char(']') => Action::CategoryNext,
        KeyCode::Char('i') => Action::ToggleCards,
        KeyCode::Char('s') => Action::Shuffle,
        KeyCode::Char('e') => Action::Repeat,
        KeyCode::Char('A') => Action::Autoplay,
        KeyCode::Char('v') => Action::ToggleQueue,
        KeyCode::Char('u') => Action::PlayNext,
        KeyCode::Char('R') => Action::Radio,
        KeyCode::Char('w') => Action::Artist,
        KeyCode::Char('f') => Action::Like,
        KeyCode::Char('d') => Action::Dislike,
        KeyCode::Char('a') => Action::AddToPlaylist,
        KeyCode::Char('x') | KeyCode::Delete => Action::Remove,
        KeyCode::Char('K') => Action::MoveUp,
        KeyCode::Char('J') => Action::MoveDown,
        KeyCode::Char('X') => Action::ClearQueue,
        KeyCode::Char('D') => Action::Download,
        KeyCode::Char('V') => Action::Video,
        KeyCode::Char('O') => Action::Sort,
        KeyCode::Char('S') => Action::SaveOrFollow,
        KeyCode::Char('m') => Action::PlaylistMenu,
        KeyCode::Char('t') => Action::Lyrics,
        KeyCode::Char('z') => Action::Sleep,
        KeyCode::Char('C') => Action::Cast,
        KeyCode::Char('1') => Action::Home,
        KeyCode::Char('2') => Action::History,
        KeyCode::Char('3') => Action::Downloads,
        KeyCode::Char('4') => Action::Albums,
        KeyCode::Char('5') => Action::Artists,
        KeyCode::Char('6') => Action::Explore,
        KeyCode::Char('L') => Action::SignIn,
        _ => return None,
    })
}
